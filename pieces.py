def afficher(T):
    if T == []:
        return ""
    l,n = len(T),len(T[1])
    for i in range(l):
        for j in range(n):
            if T[i][j] == 2:
                print("🟥",end = "")
            elif T[i][j] == 1:
                print("⬛", end = "")
            elif T[i][j] == 3:
                print("🟩",end = "")
            else:
                print("⬜", end = "")
        print("\n")
    print("\n")

